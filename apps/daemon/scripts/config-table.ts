/**
 * `bun run docs:config`: renders the configuration table in `docs/self-hosting.md` from the Zod
 * schema in `src/config.ts`, between the `config-table` markers. `--check` exits 1 instead of
 * writing when the table is out of date (part of `bun run check`).
 */
import { join } from 'node:path';
import { z } from 'zod';
import { configSchema, PRODUCTION_REQUIRED } from '../src/config.ts';

const DOC = join(import.meta.dir, '../../../docs/self-hosting.md');
const START = '<!-- config-table:start (generated by `bun run docs:config`; edit the descriptions in apps/daemon/src/config.ts) -->';
const END = '<!-- config-table:end -->';

const Property = z.object({ description: z.string(), default: z.unknown().optional() });
const Schema = z.object({ properties: z.record(z.string(), Property), required: z.array(z.string()).default([]) });

/** The Markdown table: variable, whether it must be set (always, or in production), its default, and what it does. */
function configTable(): string {
  const { properties, required } = Schema.parse(z.toJSONSchema(configSchema, { io: 'input', unrepresentable: 'any' }));
  const cell = (value: string) => value.replace(/\|/g, '\\|');
  const rows = Object.entries(properties).map(([name, p]) => {
    const fallback = p.default === undefined || p.default === '' ? '' : `\`${String(p.default)}\``;
    const must = required.includes(name) ? 'yes' : PRODUCTION_REQUIRED.some((key) => key === name) ? 'production' : '';
    return `| \`${name}\` | ${must} | ${fallback} | ${cell(p.description)} |`;
  });
  return ['| Variable | Required | Default | Meaning |', '| --- | --- | --- | --- |', ...rows].join('\n');
}

if (import.meta.main) {
  const doc = await Bun.file(DOC).text();
  const [before, rest] = doc.split(START);
  const after = rest?.split(END)[1];
  if (before === undefined || after === undefined) throw new Error(`docs/self-hosting.md lacks the config-table markers`);
  const next = `${before}${START}\n${configTable()}\n${END}${after}`;
  if (process.argv.includes('--check')) {
    if (next !== doc) {
      console.error('docs/self-hosting.md: the configuration table is stale; run `bun run docs:config`');
      process.exit(1);
    }
  } else await Bun.write(DOC, next);
}
